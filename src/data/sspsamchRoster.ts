export function buildPdfTeacherProfiles(ownerUid: string): Omit<TeacherProfile, 'createdAt' | 'updatedAt'>[] {
  const deptCycle = [
    'Rachana Sharir',
    'Ayurveda Samhita',
    'Kriya Sharir',
    'Dravyaguna Vigyana',
    'Rasashastra',
    'Kayachikitsa',
    'Panchakarma',
    'Shalya Tantra',
  ];

  return PDF_FACULTY_NAMES.map((fullName, idx) => {
    const num = String(idx + 1).padStart(3, '0');
    const cleanId = `t_pdf_${num}`;
    return {
      id: cleanId,
      ownerUid,
      fullName,
      designation:
        idx === 0
          ? 'Professor & Academic Coordinator'
          : idx < 6
            ? 'Professor & HOD'
            : idx < 13
              ? 'Associate Professor'
              : 'Assistant Professor',
      department: deptCycle[idx % deptCycle.length],
      qualification: fullName.startsWith('Mr.') ? 'M.Sc / BAMS Faculty' : 'BAMS, MD (Ayurveda)',
      employeeCode: `FAC-SSPS-${num}`,
      officeHours: 'Mon–Sat · 09:30–16:00',
      bio: `SSPSAMCH Faculty member (${deptCycle[idx % deptCycle.length]}) conducting NCISM BAMS Theory & Practical sessions.`,
      avatarUrl:
        fullName.includes('PALLAVI') ||
        fullName.includes('TRIPURA') ||
        fullName.includes('SAPANA') ||
        fullName.includes('DIVYA')
          ? '/src/assets/images/avatar_teacher_female_1794991001969.jpg'
          : '/src/assets/images/avatar_teacher_male_1794991000843.jpg',
      assignedSubjects: [],
      weeklyHours: 16,
      sessionsSubmitted: 12 + (idx % 10),
      sessionsDraft: idx % 3 === 0 ? 1 : 0,
      avgAttendanceRate: 81 + (idx % 11),
      institutionId: INSTITUTION_ID,
    };
  });
}

